package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

type config struct {
	Info struct {
		ProductName       string `yaml:"productName"`
		ProductIdentifier string `yaml:"productIdentifier"`
		Description       string `yaml:"description"`
		Version           string `yaml:"version"`
	} `yaml:"info"`
}

func main() {
	root, err := findRoot()
	if err != nil {
		fail(err)
	}
	cfg, err := load(filepath.Join(root, "build", "config.yml"))
	if err != nil {
		fail(err)
	}
	code, err := versionCode(cfg.Info.Version)
	if err != nil {
		fail(err)
	}
	if err := writeGo(root, cfg, code); err != nil {
		fail(err)
	}
	if err := writeProperties(root, cfg, code); err != nil {
		fail(err)
	}
	fmt.Printf("appinfo: %s %s (%d) %s\n",
		cfg.Info.ProductName, cfg.Info.Version, code, cfg.Info.ProductIdentifier)
}

func findRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod above the working directory")
		}
		dir = parent
	}
}

func load(path string) (config, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return config{}, err
	}
	var cfg config
	if err := yaml.Unmarshal(data, &cfg); err != nil {
		return config{}, fmt.Errorf("%s: %w", path, err)
	}
	for name, value := range map[string]string{
		"productName":       cfg.Info.ProductName,
		"productIdentifier": cfg.Info.ProductIdentifier,
		"description":       cfg.Info.Description,
		"version":           cfg.Info.Version,
	} {
		if strings.TrimSpace(value) == "" {
			return config{}, fmt.Errorf("%s: info.%s is empty", path, name)
		}
	}
	return cfg, nil
}

func versionCode(version string) (int, error) {
	parts := strings.SplitN(strings.TrimSpace(version), ".", 3)
	if len(parts) != 3 {
		return 0, fmt.Errorf("version %q is not major.minor.patch", version)
	}
	out := 0
	for i, scale := range []int{10000, 100, 1} {
		n, err := strconv.Atoi(strings.SplitN(parts[i], "-", 2)[0])
		if err != nil || n < 0 || n > 99 {
			return 0, fmt.Errorf("version %q has a bad component %q", version, parts[i])
		}
		out += n * scale
	}
	return out, nil
}

func writeGo(root string, cfg config, code int) error {
	body := fmt.Sprintf(`// Code generated by build/tools/appinfo. DO NOT EDIT.

package appinfo

const (
	Name        = %q
	Description = %q
	Identifier  = %q
	Version     = %q
	VersionCode = %d
)
`, cfg.Info.ProductName, cfg.Info.Description, cfg.Info.ProductIdentifier, cfg.Info.Version, code)
	return write(filepath.Join(root, "internal", "appinfo", "info.gen.go"), body)
}

func writeProperties(root string, cfg config, code int) error {
	body := fmt.Sprintf(`# Generated by build/tools/appinfo. DO NOT EDIT.
app.name=%s
app.applicationId=%s
app.versionName=%s
app.versionCode=%d
`, cfg.Info.ProductName, cfg.Info.ProductIdentifier, cfg.Info.Version, code)
	return write(filepath.Join(root, "build", "android", "app", "appinfo.properties"), body)
}

func write(path, body string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if old, err := os.ReadFile(path); err == nil && string(old) == body {
		return nil
	}
	return os.WriteFile(path, []byte(body), 0o644)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "appinfo:", err)
	os.Exit(1)
}
